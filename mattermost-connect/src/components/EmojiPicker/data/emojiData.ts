// Récupérer le nom d'API d'un emoji
export const getEmojiName = (emoji: string): string => {
  return EMOJI_NAMES[emoji] || emoji;
};

// Récupérer l'emoji à partir de son nom d'API
export const getEmojiFromName = (name: string): string | undefined => {
  const entry = Object.entries(EMOJI_NAMES).find(
    ([_, emojiName]) => emojiName === name,
  );
  return entry ? entry[0] : undefined;
};

